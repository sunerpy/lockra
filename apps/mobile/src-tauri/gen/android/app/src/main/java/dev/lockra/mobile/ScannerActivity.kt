import java.util.concurrent.Executors
import java.util.concurrent.atomic.AtomicBoolean
import java.util.concurrent.atomic.AtomicReference

/**
 * The camera, looking for a QR code (ScannerPlugin opens it). It answers the plugin's call itself,
 * exactly once: with the first code read (`text`; it stays in this process, no Intent carries it),
 * or with how the scan ended: `left` (back, cancel), `away` (another app in front, the home
 * screen, the screen off: Rust locks the vault), `denied` (the camera permission) or `noCamera`.
 * Like MainActivity, it never shows in screenshots or the recent apps. Not generated by
 * `cargo tauri android init`: keep this file when regenerating the project.
 */
class ScannerActivity : ComponentActivity() {
    companion object {
        const val EXTRA_PROMPT = "dev.lockra.mobile.scan.prompt"
        const val EXTRA_CANCEL = "dev.lockra.mobile.scan.cancel"
        private val HINTS = mapOf<DecodeHintType, Any>(DecodeHintType.TRY_HARDER to true)
        private val pending = AtomicReference<Invoke?>(null)

        /** Take the call this page answers; `false` while another scan is open. */
        fun begin(invoke: Invoke): Boolean = pending.compareAndSet(null, invoke)

        private fun answer(fill: JSObject.() -> Unit) {
            pending.getAndSet(null)?.resolve(JSObject().apply(fill))
        }
    }

    private val reader = QRCodeReader()
    private val ended = AtomicBoolean(false)
    private lateinit var analysis: ExecutorService
    private lateinit var preview: PreviewView
    private val permission = registerForActivityResult(ActivityResultContracts.RequestPermission()) { granted ->
        if (granted) startCamera() else end { put("denied", true) }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        // The picture shows the codes it is pointed at.
        window.setFlags(WindowManager.LayoutParams.FLAG_SECURE, WindowManager.LayoutParams.FLAG_SECURE)
        enableEdgeToEdge()
        super.onCreate(savedInstanceState)
        analysis = Executors.newSingleThreadExecutor()
        setContentView(layout(intent.getStringExtra(EXTRA_PROMPT).orEmpty(), intent.getStringExtra(EXTRA_CANCEL).orEmpty()))
        onBackPressedDispatcher.addCallback(this, object : OnBackPressedCallback(true) {
            override fun handleOnBackPressed() = end { put("left", true) }
        })
        when {
            !packageManager.hasSystemFeature(PackageManager.FEATURE_CAMERA_ANY) -> end { put("noCamera", true) }
            ContextCompat.checkSelfPermission(this, Manifest.permission.CAMERA) == PackageManager.PERMISSION_GRANTED -> startCamera()
            else -> permission.launch(Manifest.permission.CAMERA)
        }
    }

    override fun onStop() {
        super.onStop()
        // The permission prompt only pauses this page, and a rotation does not restart it
        // (configChanges in the manifest): stopped, the app was left.
        if (!isFinishing) end { put("away", true) }
    }

    override fun onDestroy() {
        super.onDestroy()
        analysis.shutdown()
        // However the page went, Rust is not left waiting.
        answer { put("left", true) }
    }

    private fun end(fill: JSObject.() -> Unit) {
        if (ended.compareAndSet(false, true)) answer(fill)
        finish()
    }

    private fun startCamera() {
        val future = ProcessCameraProvider.getInstance(this)
        future.addListener({
            if (ended.get()) return@addListener
            try {
                val provider = future.get()
                val shown = Preview.Builder().build().also { it.setSurfaceProvider(preview.surfaceProvider) }
                // Large enough for the dense codes of a Google export.
                val resolution = ResolutionSelector.Builder()
                    .setResolutionStrategy(ResolutionStrategy(Size(1280, 720), ResolutionStrategy.FALLBACK_RULE_CLOSEST_HIGHER_THEN_LOWER))
                    .build()
                val read = ImageAnalysis.Builder()
                    .setResolutionSelector(resolution)
                    .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                    .build()
                    .also { it.setAnalyzer(analysis, ::analyze) }
                provider.unbindAll()
                provider.bindToLifecycle(this, CameraSelector.DEFAULT_BACK_CAMERA, shown, read)
            } catch (e: Exception) {
                end { put("noCamera", true) }
            }
        }, ContextCompat.getMainExecutor(this))
    }

    /** One frame: its luminance, searched for a QR code. */
    private fun analyze(image: ImageProxy) {
        image.use { frame ->
            if (ended.get()) return
            val plane = frame.planes[0]
            val buffer = plane.buffer
            val luminance = ByteArray(buffer.remaining())
            buffer.get(luminance)
            val source = PlanarYUVLuminanceSource(luminance, plane.rowStride, frame.height, 0, 0, frame.width, frame.height, false)
            val text = try {
                reader.decode(BinaryBitmap(HybridBinarizer(source)), HINTS).text
            } catch (_: ReaderException) {
                null
            } finally {
                reader.reset()
            }
            if (text != null) runOnUiThread { end { put("text", text) } }
        }
    }

    /** The picture, and over its bottom the prompt and the way out, clear of the navigation bar. */
    private fun layout(prompt: String, cancel: String): View {
        val density = resources.displayMetrics.density
        fun dp(value: Int) = (value * density).toInt()
        // A TextureView: unlike a SurfaceView, part of the window that FLAG_SECURE keeps out of
        // screenshots.
        preview = PreviewView(this).apply {
            implementationMode = PreviewView.ImplementationMode.COMPATIBLE
            scaleType = PreviewView.ScaleType.FILL_CENTER
        }
        val words = TextView(this).apply {
            text = prompt
            textSize = 16f
            gravity = Gravity.CENTER
            setTextColor(Color.WHITE)
            setShadowLayer(4f, 0f, 1f, Color.BLACK)
        }
        val leave = Button(this).apply {
            text = cancel
            isAllCaps = false
            setOnClickListener { end { put("left", true) } }
        }
        val bar = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            gravity = Gravity.CENTER_HORIZONTAL
            addView(words, LinearLayout.LayoutParams(MATCH_PARENT, WRAP_CONTENT))
            addView(leave, LinearLayout.LayoutParams(WRAP_CONTENT, WRAP_CONTENT).apply { topMargin = dp(16) })
        }
        ViewCompat.setOnApplyWindowInsetsListener(bar) { view, insets ->
            val bars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            view.setPadding(dp(24), dp(24), dp(24), bars.bottom + dp(24))
            insets
        }
        return FrameLayout(this).apply {
            setBackgroundColor(Color.BLACK)
            addView(preview, FrameLayout.LayoutParams(MATCH_PARENT, MATCH_PARENT))
            addView(bar, FrameLayout.LayoutParams(MATCH_PARENT, WRAP_CONTENT, Gravity.BOTTOM))
        }
    }
}
