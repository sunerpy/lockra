package dev.lockra.mobile

import android.app.Activity
import android.content.ClipData
import android.content.ClipDescription
import android.content.ClipboardManager
import android.content.Context
import android.os.Build
import android.os.PersistableBundle
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin

@InvokeArg
class WriteSecretArgs {
    var text: String = ""
}

@InvokeArg
class ClearIfArgs {
    var expected: String = ""
}

/**
 * The phone's clipboard as the core's port (src/clipboard.rs calls these from Rust; the webview
 * cannot). A code goes on marked sensitive, so the system's paste preview and the keyboard's
 * clipboard history keep it out of sight, and comes off again only while it is still that code.
 * Android 10+ lets an app read the clipboard only while it is in front: in the background
 * `clearIf` clears only when nothing was copied since Lockra's own write, as far as this app
 * heard. Not generated by `cargo tauri android init`: keep this file when regenerating the project.
 */
@TauriPlugin
class ClipboardPlugin(private val activity: Activity) : Plugin(activity) {
    private val manager = activity.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
    private var written: String? = null
    private var changedSince = false
    private val listener = ClipboardManager.OnPrimaryClipChangedListener {
        if (written != null && currentText() != written) changedSince = true
    }

    init {
        manager.addPrimaryClipChangedListener(listener)
    }

    private fun currentText(): String? {
        val clip = manager.primaryClip ?: return null
        if (clip.itemCount == 0) return null
        return clip.getItemAt(0).coerceToText(activity)?.toString()
    }

    @Command
    fun writeSecret(invoke: Invoke) {
        val args = invoke.parseArgs(WriteSecretArgs::class.java)
        val clip = ClipData.newPlainText("Lockra", args.text)
        clip.description.extras = PersistableBundle().apply {
            val key = if (Build.VERSION.SDK_INT >= 33) ClipDescription.EXTRA_IS_SENSITIVE else "android.content.extra.IS_SENSITIVE"
            putBoolean(key, true)
        }
        written = args.text
        changedSince = false
        manager.setPrimaryClip(clip)
        invoke.resolve()
    }

    @Command
    fun readText(invoke: Invoke) {
        val ret = JSObject()
        ret.put("text", currentText())
        invoke.resolve(ret)
    }

    @Command
    fun clearIf(invoke: Invoke) {
        val args = invoke.parseArgs(ClearIfArgs::class.java)
        val current = currentText()
        val ours = if (current != null) current == args.expected else written == args.expected && !changedSince
        if (ours) {
            if (Build.VERSION.SDK_INT >= 28) manager.clearPrimaryClip() else manager.setPrimaryClip(ClipData.newPlainText("", ""))
            written = null
        }
        val ret = JSObject()
        ret.put("cleared", ours)
        invoke.resolve(ret)
    }
}
