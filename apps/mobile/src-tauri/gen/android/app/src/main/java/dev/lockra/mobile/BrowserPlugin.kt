package dev.lockra.mobile

import android.app.Activity
import android.content.ActivityNotFoundException
import android.content.Intent
import android.net.Uri
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin

@InvokeArg
class OpenArgs {
    var url: String = ""
}

/**
 * The phone's browser for one page, a Lockra release's, or Lockra's Google Play listing, which opens
 * in the Play app where there is one (src/browser.rs calls `open` from Rust with the address it
 * made; the webview cannot). Any other address is refused. Answers `{ opened }`: false when no app
 * on the phone opens it. Leaving for the browser or Play locks the vault, as leaving for any other
 * app does. Not generated by `cargo tauri android init`: keep this file when regenerating the
 * project.
 */
@TauriPlugin
class BrowserPlugin(private val activity: Activity) : Plugin(activity) {
    @Command
    fun open(invoke: Invoke) {
        val args = invoke.parseArgs(OpenArgs::class.java)
        val listing = args.url == PLAY_LISTING
        if (!args.url.startsWith(RELEASES) && !listing) {
            invoke.reject("not a page of Lockra's releases")
            return
        }
        activity.runOnUiThread {
            val page = Intent(Intent.ACTION_VIEW, Uri.parse(args.url)).addCategory(Intent.CATEGORY_BROWSABLE)
            // The listing in the Play app itself, else in the browser.
            val tries = if (listing) listOf(Intent(page).setPackage(PLAY_STORE), page) else listOf(page)
            val opened = tries.any { intent ->
                try {
                    activity.startActivity(intent)
                    true
                } catch (e: ActivityNotFoundException) {
                    false
                }
            }
            invoke.resolve(JSObject().put("opened", opened))
        }
    }

    private companion object {
        const val RELEASES = "https://github.com/sunerpy/lockra/releases/"
        const val PLAY_LISTING = "https://play.google.com/store/apps/details?id=dev.lockra.mobile"
        const val PLAY_STORE = "com.android.vending"
    }
}
