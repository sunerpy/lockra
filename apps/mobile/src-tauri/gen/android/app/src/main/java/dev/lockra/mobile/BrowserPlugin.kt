package dev.lockra.mobile

import android.app.Activity
import android.content.ActivityNotFoundException
import android.content.Intent
import android.net.Uri
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin

@InvokeArg
class OpenArgs {
    var url: String = ""
}

/**
 * The phone's browser for one page, a Lockra release's (src/browser.rs calls `open` from Rust with
 * the address it made; the webview cannot). Any other address is refused. Answers `{ opened }`:
 * false when no app on the phone opens web pages. Leaving for the browser locks the vault, as
 * leaving for any other app does. Not generated by `cargo tauri android init`: keep this file when
 * regenerating the project.
 */
@TauriPlugin
class BrowserPlugin(private val activity: Activity) : Plugin(activity) {
    @Command
    fun open(invoke: Invoke) {
        val args = invoke.parseArgs(OpenArgs::class.java)
        if (!args.url.startsWith(RELEASES)) {
            invoke.reject("not a page of Lockra's releases")
            return
        }
        activity.runOnUiThread {
            val intent = Intent(Intent.ACTION_VIEW, Uri.parse(args.url)).addCategory(Intent.CATEGORY_BROWSABLE)
            val opened = try {
                activity.startActivity(intent)
                true
            } catch (e: ActivityNotFoundException) {
                false
            }
            invoke.resolve(JSObject().put("opened", opened))
        }
    }

    private companion object {
        const val RELEASES = "https://github.com/sunerpy/lockra/releases/"
    }
}
