package dev.lockra.mobile

import android.app.Activity
import android.net.Uri
import android.provider.OpenableColumns
import android.util.Base64
import androidx.activity.result.ActivityResult
import androidx.activity.result.PickVisualMediaRequest
import androidx.activity.result.contract.ActivityResultContracts
import app.tauri.annotation.ActivityCallback
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSArray
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin
import java.io.ByteArrayOutputStream
import java.io.IOException
import kotlin.concurrent.thread

@InvokeArg
class PickImagesArgs {
    var limit: Int = 10
    var maxBytes: Long = 0
}

@InvokeArg
class PickFilesArgs {
    var maxBytes: Long = 0
}

/**
 * The phone's pickers for the import (src/files.rs calls them from Rust; the webview cannot):
 * `pickImages` opens the photo picker and `pickFiles` the system's file picker, neither of which
 * needs a storage permission; both answer with the files' names and bytes (Base64), never a path.
 * Each file is read to one byte past `maxBytes`, enough for Rust to tell it is too large. Not
 * generated by `cargo tauri android init`: keep this file when regenerating the project.
 */
@TauriPlugin
class FilesPlugin(private val activity: Activity) : Plugin(activity) {
    private var images = ActivityResultContracts.PickMultipleVisualMedia()
    private val documents = ActivityResultContracts.OpenMultipleDocuments()
    private var maxBytes = 0L

    @Command
    fun pickImages(invoke: Invoke) {
        val args = invoke.parseArgs(PickImagesArgs::class.java)
        // The contract takes more than one image or none at all.
        images = ActivityResultContracts.PickMultipleVisualMedia(args.limit.coerceAtLeast(2))
        maxBytes = args.maxBytes
        val request = PickVisualMediaRequest(ActivityResultContracts.PickVisualMedia.ImageOnly)
        startActivityForResult(invoke, images.createIntent(activity, request), "picked")
    }

    @Command
    fun pickFiles(invoke: Invoke) {
        val args = invoke.parseArgs(PickFilesArgs::class.java)
        maxBytes = args.maxBytes
        // Every kind of file: a Lockra backup or Microsoft's database has no type to filter by.
        startActivityForResult(invoke, documents.createIntent(activity, arrayOf("*/*")), "pickedFiles")
    }

    @ActivityCallback
    fun picked(invoke: Invoke, result: ActivityResult) {
        answer(invoke, images.parseResult(result.resultCode, result.data))
    }

    @ActivityCallback
    fun pickedFiles(invoke: Invoke, result: ActivityResult) {
        answer(invoke, documents.parseResult(result.resultCode, result.data))
    }

    private fun answer(invoke: Invoke, uris: List<Uri>) {
        val count = maxBytes + 1
        // Off the activity's thread: the images may be large.
        thread {
            try {
                val files = JSArray()
                for (uri in uris) {
                    val file = JSObject()
                    file.put("name", nameOf(uri))
                    file.put("data", Base64.encodeToString(read(uri, count), Base64.NO_WRAP))
                    files.put(file)
                }
                val answer = JSObject()
                answer.put("files", files)
                invoke.resolve(answer)
            } catch (e: Exception) {
                invoke.reject(e.message ?: "the images could not be read")
            }
        }
    }

    private fun nameOf(uri: Uri): String =
        activity.contentResolver.query(uri, arrayOf(OpenableColumns.DISPLAY_NAME), null, null, null)?.use { cursor ->
            if (cursor.moveToFirst()) cursor.getString(0) else null
        } ?: uri.lastPathSegment ?: "image"

    /** At most `count` bytes of the file. */
    private fun read(uri: Uri, count: Long): ByteArray {
        val input = activity.contentResolver.openInputStream(uri) ?: throw IOException("$uri cannot be opened")
        return input.use { stream ->
            val out = ByteArrayOutputStream()
            val buffer = ByteArray(64 * 1024)
            var total = 0L
            while (total < count) {
                val n = stream.read(buffer, 0, minOf(buffer.size.toLong(), count - total).toInt())
                if (n < 0) break
                out.write(buffer, 0, n)
                total += n
            }
            out.toByteArray()
        }
    }
}
