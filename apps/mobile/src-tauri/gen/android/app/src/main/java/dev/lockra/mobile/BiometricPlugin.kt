package dev.lockra.mobile

import android.app.Activity
import android.content.Context
import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyPermanentlyInvalidatedException
import android.security.keystore.KeyProperties
import android.util.Base64
import androidx.biometric.BiometricManager
import androidx.biometric.BiometricManager.Authenticators.BIOMETRIC_STRONG
import androidx.biometric.BiometricPrompt
import androidx.core.content.ContextCompat
import androidx.fragment.app.FragmentActivity
import app.tauri.annotation.Command
import app.tauri.annotation.InvokeArg
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

@InvokeArg
class VerifyArgs {
    var reason: String = ""
}

@InvokeArg
class SecretArgs {
    var account: String = ""
    var secret: String = ""
}

/**
 * The fingerprint (src/biometrics.rs calls it from Rust; the webview cannot): `status` says whether
 * a strong biometric is enrolled, `verify` asks for one with the system's prompt. The remembered
 * key lives in this app's private preferences, sealed with AES-GCM by a key of the Android Keystore
 * that the secure hardware holds: it works only for ten seconds after a passed check, and never
 * again once a new fingerprint is enrolled (the stored key then reads as gone, and the master
 * password unlocks). Not generated by `cargo tauri android init`: keep this file when regenerating
 * the project.
 */
@TauriPlugin
class BiometricPlugin(private val activity: Activity) : Plugin(activity) {
    companion object {
        private const val ALIAS = "lockra-device-key"
        private const val PREFERENCES = "lockra-device-keys"
        private const val SECONDS = 10
        private const val CIPHER = "AES/GCM/NoPadding"
    }

    private val preferences get() = activity.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE)

    @Command
    fun status(invoke: Invoke) {
        val strong = BiometricManager.from(activity).canAuthenticate(BIOMETRIC_STRONG) == BiometricManager.BIOMETRIC_SUCCESS
        invoke.resolve(JSObject().apply { put("strong", strong) })
    }

    @Command
    fun verify(invoke: Invoke) {
        val args = invoke.parseArgs(VerifyArgs::class.java)
        val host = activity as? FragmentActivity
        if (host == null) {
            invoke.resolve(JSObject().apply { put("unavailable", true) })
            return
        }
        activity.runOnUiThread {
            val callback = object : BiometricPrompt.AuthenticationCallback() {
                override fun onAuthenticationSucceeded(result: BiometricPrompt.AuthenticationResult) {
                    invoke.resolve(JSObject().apply { put("ok", true) })
                }

                override fun onAuthenticationError(code: Int, message: CharSequence) {
                    invoke.resolve(
                        JSObject().apply {
                            when (code) {
                                BiometricPrompt.ERROR_USER_CANCELED,
                                BiometricPrompt.ERROR_NEGATIVE_BUTTON,
                                BiometricPrompt.ERROR_CANCELED -> put("cancelled", true)
                                BiometricPrompt.ERROR_LOCKOUT,
                                BiometricPrompt.ERROR_LOCKOUT_PERMANENT,
                                BiometricPrompt.ERROR_NO_BIOMETRICS,
                                BiometricPrompt.ERROR_HW_UNAVAILABLE,
                                BiometricPrompt.ERROR_HW_NOT_PRESENT -> put("unavailable", true)
                                else -> put("failed", message.toString())
                            }
                        },
                    )
                }
                // A finger not recognised: the prompt says so and waits for another.
            }
            val info = BiometricPrompt.PromptInfo.Builder()
                .setTitle("Lockra")
                .setSubtitle(args.reason)
                .setNegativeButtonText(activity.getString(android.R.string.cancel))
                .setAllowedAuthenticators(BIOMETRIC_STRONG)
                .setConfirmationRequired(false)
                .build()
            BiometricPrompt(host, ContextCompat.getMainExecutor(activity), callback).authenticate(info)
        }
    }

    @Command
    fun setSecret(invoke: Invoke) {
        val args = invoke.parseArgs(SecretArgs::class.java)
        try {
            val cipher = try {
                encrypting(key(create = true))
            } catch (e: KeyPermanentlyInvalidatedException) {
                // A key from before a new fingerprint: a new one takes its place.
                deleteKey()
                encrypting(key(create = true))
            }
            val sealed = cipher.doFinal(args.secret.toByteArray(Charsets.UTF_8))
            val value = Base64.encodeToString(cipher.iv, Base64.NO_WRAP) + ":" + Base64.encodeToString(sealed, Base64.NO_WRAP)
            // Written before the answer: the core writes the vault's device slot next.
            if (!preferences.edit().putString(args.account, value).commit()) throw IllegalStateException("the key was not written")
            invoke.resolve(JSObject())
        } catch (e: Exception) {
            invoke.reject(e.message ?: "the key could not be stored")
        }
    }

    @Command
    fun getSecret(invoke: Invoke) {
        val args = invoke.parseArgs(SecretArgs::class.java)
        val stored = preferences.getString(args.account, null)
        val key = key(create = false)
        if (stored == null || key == null) {
            invoke.resolve(JSObject())
            return
        }
        try {
            val parts = stored.split(":", limit = 2)
            val cipher = Cipher.getInstance(CIPHER)
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(128, Base64.decode(parts[0], Base64.NO_WRAP)))
            val secret = String(cipher.doFinal(Base64.decode(parts[1], Base64.NO_WRAP)), Charsets.UTF_8)
            invoke.resolve(JSObject().apply { put("secret", secret) })
        } catch (e: KeyPermanentlyInvalidatedException) {
            // A new fingerprint was enrolled: the key is gone for good, and so is what it sealed.
            preferences.edit().clear().commit()
            deleteKey()
            invoke.resolve(JSObject())
        } catch (e: Exception) {
            invoke.reject(e.message ?: "the key could not be read")
        }
    }

    @Command
    fun deleteSecret(invoke: Invoke) {
        val args = invoke.parseArgs(SecretArgs::class.java)
        preferences.edit().remove(args.account).commit()
        if (preferences.all.isEmpty()) deleteKey()
        invoke.resolve(JSObject())
    }

    private fun encrypting(key: SecretKey?): Cipher {
        val cipher = Cipher.getInstance(CIPHER)
        cipher.init(Cipher.ENCRYPT_MODE, key ?: throw IllegalStateException("no key"))
        return cipher
    }

    /** The Keystore key, made when asked to and there is none. */
    private fun key(create: Boolean): SecretKey? {
        val store = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (store.getKey(ALIAS, null) as? SecretKey)?.let { return it }
        if (!create) return null
        val spec = KeyGenParameterSpec.Builder(ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setUserAuthenticationRequired(true)
            .setInvalidatedByBiometricEnrollment(true)
            .apply {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
                    setUserAuthenticationParameters(SECONDS, KeyProperties.AUTH_BIOMETRIC_STRONG)
                } else {
                    @Suppress("DEPRECATION")
                    setUserAuthenticationValidityDurationSeconds(SECONDS)
                }
            }
            .build()
        return KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore").apply { init(spec) }.generateKey()
    }

    private fun deleteKey() {
        val store = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        if (store.containsAlias(ALIAS)) store.deleteEntry(ALIAS)
    }
}
