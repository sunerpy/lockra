package dev.lockra.mobile

import android.app.Activity
import android.os.Build
import app.tauri.annotation.Command
import app.tauri.annotation.TauriPlugin
import app.tauri.plugin.Invoke
import app.tauri.plugin.JSObject
import app.tauri.plugin.Plugin

/**
 * Who installed this app, for the in-app update (src/updater.rs asks once, off the setup thread,
 * after Voltip's UpdatePlugin): `com.android.vending` is Google Play, which updates the app itself;
 * anything else (the browser or file manager that opened a GitHub release's APK, or adb) means the
 * app looks for new releases on GitHub. Asked over JNI rather than handed over in the environment:
 * an arm64 app translated on an x86 device (an emulator, a Chromebook) has a libc of its own, which
 * does not see what the Java side set. Not generated by `cargo tauri android init`: keep this file
 * when regenerating the project.
 */
@TauriPlugin
class UpdatePlugin(private val activity: Activity) : Plugin(activity) {
    @Command
    fun installSource(invoke: Invoke) {
        val packages = activity.packageManager
        val installer = try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
                packages.getInstallSourceInfo(activity.packageName).installingPackageName
            } else {
                @Suppress("DEPRECATION")
                packages.getInstallerPackageName(activity.packageName)
            }
        } catch (e: Exception) {
            null
        }
        val ret = JSObject()
        // No installer on record (adb, a system image): the key stays out and reads as none.
        if (installer != null) ret.put("installer", installer)
        invoke.resolve(ret)
    }
}
