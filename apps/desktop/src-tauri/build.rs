use std::path::{Path, PathBuf};

/// The release legs set it: the build must carry the extension, of the release's version.
const REQUIRED_ENV: &str = "LOCKRA_EXTENSION_REQUIRED";

fn main() {
    tauri_build::build();
    embed_extension();
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    // tauri-build links the Windows resource (icon, version, and the manifest that asks for Common
    // Controls v6) into the application binary only. tauri-plugin-dialog's message dialogs import
    // `TaskDialogIndirect`, which only Common Controls v6 has: tests/ipc.rs would not even start
    // without the manifest (STATUS_ENTRYPOINT_NOT_FOUND). The test binaries get the same resource.
    if target_os == "windows" {
        let resource = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("resource.lib");
        if resource.exists() {
            println!("cargo:rustc-link-arg-tests={}", resource.display());
        }
    }
    // Static CRT (.cargo/config.toml `+crt-static`) and the Tauri CLI's hybrid CRT on top of it: the
    // vcruntime static, the UCRT from Windows (`/DEFAULTLIB:ucrt.lib`). MSVC's link.exe on Windows takes
    // that as it is. A Linux host cross-building with cargo-xwin links with lld-link, where the hybrid
    // `/DEFAULTLIB:ucrt.lib` resolves nothing (the link failed on `strlen` and `round`), so only there
    // the static UCRT is named. Naming it on Windows as well defines the UCRT twice: link.exe stopped
    // with LNK2005 on `__p___argc` in the v0.1.0 release run (2026-10-01).
    let cross_from_unix = std::env::var("HOST").is_ok_and(|host| !host.contains("windows"));
    let crt_static = std::env::var("CARGO_CFG_TARGET_FEATURE").is_ok_and(|f| f.split(',').any(|x| x == "crt-static"));
    if target_os == "windows" && crt_static && cross_from_unix {
        println!("cargo:rustc-link-arg=libucrt.lib");
    }
}

/// The Chromium build of the extension that Lockra keeps in the folder the user loads unpacked
/// (src/browser/extension.rs): every file of `apps/extension/dist/chromium-unpacked/`, written into
/// `$OUT_DIR/extension.rs` as `FILES`. None when it has not been built (a development or test
/// build: `tauri.conf.json`'s `beforeBuildCommand` builds it for every `tauri build`). With
/// [`REQUIRED_ENV`] at `1` a missing build, or one of another version than the root
/// `package.json`'s, stops the build.
///
/// The folder is watched only once it exists: Cargo runs a build script whose watched path is
/// missing at every build, and the crate with it. A build made before the extension was gets it
/// when the script runs again (`touch build.rs`, or [`REQUIRED_ENV`] set).
fn embed_extension() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let dir = manifest_dir.join("../../extension/dist/chromium-unpacked");
    println!("cargo:rerun-if-env-changed={REQUIRED_ENV}");
    let required = std::env::var(REQUIRED_ENV).is_ok_and(|value| value == "1");
    let mut files = Vec::new();
    if dir.join("manifest.json").is_file() {
        println!("cargo:rerun-if-changed={}", dir.display());
        collect(&dir, &dir, &mut files);
        files.sort();
    }
    if required {
        let version = |path: &Path| -> Option<String> {
            let json: serde_json::Value = serde_json::from_slice(&std::fs::read(path).ok()?).ok()?;
            json.get("version")?.as_str().map(str::to_owned)
        };
        let Some(release) = version(&manifest_dir.join("../../../package.json")) else { panic!("{REQUIRED_ENV}: the root package.json names no version") };
        match version(&dir.join("manifest.json")) {
            Some(built) if built == release => {}
            Some(built) => panic!("{REQUIRED_ENV}: the extension in {} is {built}, the release {release}: build it again", dir.display()),
            None => panic!("{REQUIRED_ENV}: no extension in {}: pnpm --filter @lockra/extension run build", dir.display()),
        }
    }
    let mut out = String::from("// Generated by build.rs: apps/extension/dist/chromium-unpacked, file by file.\npub static FILES: &[(&str, &[u8])] = &[\n");
    for (name, path) in &files {
        out.push_str(&format!("    ({name:?}, include_bytes!({:?})),\n", path.display().to_string()));
    }
    out.push_str("];\n");
    let target = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("extension.rs");
    if let Err(error) = std::fs::write(&target, out) {
        panic!("{}: {error}", target.display());
    }
}

/// Every file under `dir`, by its path from `root` with `/` between the parts.
fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = std::fs::read_dir(dir).unwrap_or_else(|error| panic!("{}: {error}", dir.display()));
    for entry in entries {
        let path = entry.unwrap_or_else(|error| panic!("{}: {error}", dir.display())).path();
        if path.is_dir() {
            collect(root, &path, files);
        } else {
            let name =
                path.strip_prefix(root).unwrap_or(&path).components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("/");
            files.push((name, path));
        }
    }
}
